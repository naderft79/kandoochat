export type SettingKey = keyof typeof DEFAULT_SETTINGS;

// خواندن یک تنظیم
export async function getSetting(key: SettingKey): Promise<number> {
  const row = await prisma.setting.findUnique({ where: { key } });
  return parseInt(row?.value ?? DEFAULT_SETTINGS[key], 10);
}

// cache در حافظه برای getAllSettings — TTL 30 ثانیه
let settingsCache: { data: Record<string, unknown>; expiry: number } | null = null;
const SETTINGS_CACHE_TTL = 30_000; // 30 ثانیه

// خواندن همه تنظیمات
export async function getAllSettings() {
  // بررسی cache
  if (settingsCache && Date.now() < settingsCache.expiry) {
    return settingsCache.data as ReturnType<typeof buildSettings>;
  }

  const rows = await prisma.setting.findMany();
  const map = new Map(rows.map((r) => [r.key, r.value]));
  const data = buildSettings(map);
  settingsCache = { data: data as Record<string, unknown>, expiry: Date.now() + SETTINGS_CACHE_TTL };
  return data;
}

// invalid کردن cache بعد از ذخیره تنظیمات جدید
export function invalidateSettingsCache() {
  settingsCache = null;
}

