// ذخیره یک تنظیم
export async function setSetting(key: SettingKey, value: string) {
  await prisma.setting.upsert({
    where: { key },
    update: { value },
    create: { key, value },
  });
  invalidateSettingsCache();
}

// هزینه اشتراک بر حسب سکه (رو به بالا گرد می شود)
export async function getSubscriptionCoinCost() {
  const { coinValue, subscriptionPrice } = await getAllSettings();
  return Math.ceil(subscriptionPrice / coinValue);
}
