#!/usr/bin/env node
// تولید خروجی های برند — از روی src/config/brands.json
// خروجی: android/app/brands.gradle + سورس ست هر برند (strings، آیکون، capacitor.config) + کی استورها
// اجرا: node scripts/brands-generate.mjs [--icons-only]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const brandsPath = path.join(root, "src/config/brands.json");
const androidApp = path.join(root, "android/app");
const keystoresDir = path.join(root, "android/keystores");

const MARKETS = ["bazaar", "myket"];

// ---------- خواندن و اعتبارسنجی کانفیگ ----------
const config = JSON.parse(readFileSync(brandsPath, "utf8"));
const brands = config.brands ?? [];

const errors = [];
const ids = new Set();
const pkgs = new Set();
const idRe = /^[a-z][a-z0-9]{1,19}$/;
const pkgRe = /^[a-z][a-z0-9]*(\.[a-z][a-z0-9]*)+$/;
const colorRe = /^#[0-9a-fA-F]{6}$/;

for (const b of brands) {
  if (!idRe.test(b.id ?? "")) errors.push(`brand id invalid: ${b.id}`);
  if (!b.name?.trim()) errors.push(`brand ${b.id}: name required`);
  if (!pkgRe.test(b.packageName ?? "")) errors.push(`brand ${b.id}: packageName invalid: ${b.packageName}`);
  for (const k of ["primary", "light", "dark"]) {
    if (!colorRe.test(b.colors?.[k] ?? "")) errors.push(`brand ${b.id}: colors.${k} invalid`);
  }
  if (ids.has(b.id)) errors.push(`duplicate brand id: ${b.id}`);
  if (pkgs.has(b.packageName)) errors.push(`duplicate packageName: ${b.packageName}`);
  ids.add(b.id);
  pkgs.add(b.packageName);
}
if (ids.has("kandoo")) errors.push(`"kandoo" is reserved — it is the main brand, do not add it to brands.json`);
if (pkgs.has("com.kandoochats.app") || pkgs.has("com.kandoo.admin")) errors.push("packageName conflicts with kandoo user/admin app");

if (errors.length) {
  console.error("[brands] config errors:");
  errors.forEach((e) => console.error("  -", e));
  process.exit(1);
}
console.log(`[brands] ${brands.length} brand(s) configured: ${[...ids].join(", ")}`);

const cap = (s) => s[0].toUpperCase() + s.slice(1);
const flavor = (brand, market) => `${brand.id}${cap(market)}`;

// ---------- brands.gradle ----------
const flavorsBlock = brands
  .map(
    (b) => `        ${b.id} {
            dimension "brand"
            applicationId "${b.packageName}"
        }`
  )
  .join("\n");

// فقط ترکیب های مجاز نگه داشته می شوند: userDirect، adminDirect و <brand><Market>
const keepExpr = brands.length
  ? `variant.flavorName in ["userDirect", "adminDirect"] || variant.flavorName ==~ /(${brands.map((b) => b.id).join("|")})(Bazaar|Myket)/`
  : `variant.flavorName in ["userDirect", "adminDirect"]`;

const signingBlock = brands
  .map(
    (b) => `        ${b.id} {
            def p = loadProps("keystore-${b.id}.properties")
            if (p != null) {
                storeFile rootProject.file(p['storeFile'])
                storePassword p['storePassword']
                keyAlias p['keyAlias']
                keyPassword p['keyPassword']
            }
        }`
  )
  .join("\n");

const flavorSigning = brands
  .map((b) => `        ${b.id} { signingConfig signingConfigs.${b.id} }`)
  .join("\n");

const brandsGradle = `// AUTO-GENERATED by scripts/brands-generate.mjs — do not edit manually
// خروجی گریدل ماتریس برند×مارکت از روی src/config/brands.json

// امضای هر برند از فایل keystore-<brand>.properties در ریشه پروژه اندروید
def loadProps = { String name ->
    def f = rootProject.file(name)
    if (!f.exists()) return null
    def p = new Properties()
    f.withInputStream { p.load(it) }
    return p
}

android {
    signingConfigs {
${signingBlock}
    }
    productFlavors {
${flavorsBlock}
    }
    // امضای هر برند روی فلیور برند اعمال می شود — هر دو خروجی بازار و مایکت یک کی استور دارند
    productFlavors {
${flavorSigning}
    }
}

// فقط ترکیب های مجاز ساخته می شوند — بقیه فلیورهای ترکیبی غیرفعال اند
androidComponents {
    beforeVariants(selector().all()) { variant ->
        if (!(${keepExpr})) {
            variant.enable = false
        }
    }
}
`;
writeFileSync(path.join(androidApp, "brands.gradle"), brandsGradle);
console.log("[brands] wrote android/app/brands.gradle");

// ---------- سورس ست هر برند ----------
const capitalize = (s) => s[0].toUpperCase() + s.slice(1);

for (const b of brands) {
  const brandDir = path.join(androidApp, "src", b.id);
  const resDir = path.join(brandDir, "res", "values");
  const assetsDir = path.join(brandDir, "assets");
  mkdirSync(resDir, { recursive: true });
  mkdirSync(assetsDir, { recursive: true });

  // strings.xml — نام اپ، شناسه UA و کلیدهای عمومی تایید خرید هر مارکت
  writeFileSync(
    path.join(resDir, "strings.xml"),
    `<?xml version='1.0' encoding='utf-8'?>
<resources>
    <string name="app_name">${escapeXml(b.name)}</string>
    <string name="title_activity_main">${escapeXml(b.name)}</string>
    <string name="package_name">${b.packageName}</string>
    <string name="custom_url_scheme">${b.packageName}</string>
    <string name="ua_brand">${b.uaToken || b.id}</string>
    <string name="iap_public_key_bazaar">${b.iapKeys?.bazaar ?? ""}</string>
    <string name="iap_public_key_myket">${b.iapKeys?.myket ?? ""}</string>
</resources>
`
  );

  // رنگ های برند برای UI نیتیو (اسپلش و غیره)
  writeFileSync(
    path.join(resDir, "colors.xml"),
    `<?xml version='1.0' encoding='utf-8'?>
<resources>
    <color name="brand_primary">${b.colors.primary}</color>
    <color name="brand_light">${b.colors.light}</color>
    <color name="brand_dark">${b.colors.dark}</color>
</resources>
`
  );

  // capacitor.config.json مخصوص برند — appId و نام فارسی؛ UA سمت نیتیو اضافه می شود
  writeFileSync(
    path.join(assetsDir, "capacitor.config.json"),
    JSON.stringify(
      {
        appId: b.packageName,
        appName: b.name,
        webDir: "app-web",
        server: { url: "https://kandoochat.top", cleartext: false },
        android: { allowMixedContent: false, appendUserAgent: "" },
        plugins: {
          Keyboard: { resize: "native", resizeOnFullScreen: true },
          SplashScreen: {
            launchAutoHide: true,
            launchShowDuration: 0,
            backgroundColor: b.colors.primary,
          },
        },
      },
      null,
      "\t"
    )
  );
  console.log(`[brands] generated source set: android/app/src/${b.id}`);
}

// ---------- کی استور هر برند ----------
mkdirSync(keystoresDir, { recursive: true });
for (const b of brands) {
  const ksPath = path.join(keystoresDir, `${b.id}.jks`);
  const propsPath = path.join(root, "android", `keystore-${b.id}.properties`);
  const envPass = `KEYSTORE_${b.id.toUpperCase()}_PASSWORD`;
  const password = process.env[envPass] || `${b.id}-${randomPass()}`;

  if (!existsSync(ksPath)) {
    try {
      execSync(
        `keytool -genkeypair -v -keystore "${ksPath}" -alias ${b.id} -keyalg RSA -keysize 2048 -validity 10000 -storepass "${password}" -keypass "${password}" -dname "CN=${b.name}, OU=Apps, O=Kandoo, C=IR"`,
        { stdio: "pipe" }
      );
      console.log(`[brands] generated keystore: ${ksPath}`);
    } catch {
      console.warn(`[brands] keytool failed for ${b.id} — create ${ksPath} manually`);
    }
  }
  if (!existsSync(propsPath)) {
    writeFileSync(
      propsPath,
      `storeFile=keystores/${b.id}.jks\nstorePassword=${password}\nkeyAlias=${b.id}\nkeyPassword=${password}\n`
    );
    console.log(`[brands] wrote android/keystore-${b.id}.properties`);
  }
}

// ---------- آیکون های لانچر با sharp ----------
// شکل مونوگرام هر قالب — با src/lib/brand-theme.ts همگام نگه شود
const THEME_ICON = {
  aurora: { radiusRatio: 0.5, deco: "glow" },
  flame: { radiusRatio: 0.28, deco: "flame" },
  voyage: { radiusRatio: 0.22, deco: "path" },
};

function monogramSpec(b) {
  const t = THEME_ICON[b.theme] ?? THEME_ICON.voyage;
  return {
    letter: (b.iconLetter || b.name.trim()[0] || "ک"),
    primary: b.colors.primary,
    secondary: b.colors.secondary ?? b.colors.dark,
    radiusRatio: t.radius,
    deco: t.deco,
  };
}

// SVG مونوگرام — حرف اول نام + گرادیانت + المان قالب
function iconSvg(spec, px, opts = {}) {
  const r = opts.round ? px / 2 : px * spec.radiusRatio;
  const fontSize = Math.round(px * (opts.maskable ? 0.42 : 0.52));
  const deco =
    spec.deco === "glow"
      ? `<circle cx="${px / 2}" cy="${px / 2}" r="${px * 0.36}" fill="#ffffff" opacity="0.22"/>`
      : spec.deco === "flame"
        ? `<path d="M ${px * 0.2} ${px * 0.78} Q ${px * 0.5} ${px * 0.6} ${px * 0.8} ${px * 0.78}" stroke="#ffffff" stroke-width="${px * 0.03}" fill="none" opacity="0.5" stroke-linecap="round"/>`
        : spec.deco === "path"
          ? `<path d="M ${px * 0.22} ${px * 0.8} C ${px * 0.4} ${px * 0.68}, ${px * 0.6} ${px * 0.68}, ${px * 0.78} ${px * 0.8}" stroke="#ffffff" stroke-width="${px * 0.025}" fill="none" opacity="0.6" stroke-linecap="round" stroke-dasharray="${px * 0.05} ${px * 0.04}"/>`
          : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${spec.primary}"/>
      <stop offset="1" stop-color="${spec.secondary}"/>
    </linearGradient>
  </defs>
  <rect width="${px}" height="${px}" rx="${r}" fill="${opts.transparent ? "none" : "url(#g)"}"/>
  ${deco}
  <text x="50%" y="54%" text-anchor="middle" dominant-baseline="central"
    font-family="Vazirmatn, Tahoma, Segoe UI, sans-serif" font-size="${fontSize}"
    font-weight="900" fill="#ffffff">${escapeXml(spec.letter)}</text>
</svg>`;
}

// اسپلش: تمام صفحه گرادیانت برند + مونوگرام سفید مرکزی
function splashSvg(spec, w, h) {
  const icon = Math.round(Math.min(w, h) * 0.34);
  const fontSize = Math.round(icon * 0.52);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${spec.primary}"/>
      <stop offset="1" stop-color="${spec.secondary}"/>
    </linearGradient>
  </defs>
  <rect width="${w}" height="${h}" fill="url(#g)"/>
  <circle cx="${w / 2}" cy="${h / 2}" r="${icon / 2}" fill="#ffffff" opacity="0.18"/>
  <circle cx="${w / 2}" cy="${h / 2}" r="${icon * 0.42}" fill="#ffffff" opacity="0.25"/>
  <text x="${w / 2}" y="${h / 2}" text-anchor="middle" dominant-baseline="central"
    font-family="Vazirmatn, Tahoma, Segoe UI, sans-serif" font-size="${fontSize}"
    font-weight="900" fill="#ffffff">${escapeXml(spec.letter)}</text>
</svg>`;
}

// آیکون نوتیفیکیشن مونوکروم — فقط حرف سفید روی شفاف
function notificationSvg(spec, px) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}">
  <text x="50%" y="54%" text-anchor="middle" dominant-baseline="central"
    font-family="Vazirmatn, Tahoma, Segoe UI, sans-serif" font-size="${Math.round(px * 0.6)}"
    font-weight="900" fill="#ffffff">${escapeXml(spec.letter)}</text>
</svg>`;
}

async function renderPng(sharp, svg, target) {
  try {
    await sharp(Buffer.from(svg), { density: 300 }).png().toFile(target);
  } catch (e) {
    console.warn(`[brands] png failed ${target}:`, e.message);
  }
}

async function generateIcons() {
  let sharp;
  try {
    sharp = (await import("sharp")).default;
  } catch {
    console.warn("[brands] sharp not available — skipping icon generation");
    return;
  }
  const sizes = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
  // اسپلش برای همه باکت های drawable که main دارد — وگرنه نسخه خاص تری از main برنده می شود
  const splashBuckets = [
    ["drawable", 1080, 1920],
    ["drawable-port-mdpi", 480, 800],
    ["drawable-port-hdpi", 800, 1280],
    ["drawable-port-xhdpi", 1080, 1920],
    ["drawable-port-xxhdpi", 1440, 2560],
    ["drawable-port-xxxhdpi", 1920, 3200],
    ["drawable-port-night-mdpi", 480, 800],
    ["drawable-port-night-hdpi", 800, 1280],
    ["drawable-port-night-xhdpi", 1080, 1920],
    ["drawable-port-night-xxhdpi", 1440, 2560],
    ["drawable-port-night-xxxhdpi", 1920, 3200],
    ["drawable-land-mdpi", 800, 480],
    ["drawable-land-hdpi", 1280, 800],
    ["drawable-land-xhdpi", 1920, 1080],
    ["drawable-land-xxhdpi", 2560, 1440],
    ["drawable-land-xxxhdpi", 3200, 1920],
    ["drawable-land-night-mdpi", 800, 480],
    ["drawable-land-night-hdpi", 1280, 800],
    ["drawable-land-night-xhdpi", 1920, 1080],
    ["drawable-land-night-xxhdpi", 2560, 1440],
    ["drawable-land-night-xxxhdpi", 3200, 1920],
    ["drawable-night", 1080, 1920],
  ];
  for (const b of brands) {
    const spec = monogramSpec(b);
    const brandRes = path.join(androidApp, "src", b.id, "res");
    // اگر فایل مارکر وجود داشته باشد آیکون های دستی این برند دست نمی خورند
    const manual = existsSync(path.join(brandRes, ".icon-manual"));

    for (const [dpi, px] of Object.entries(sizes)) {
      const dir = path.join(brandRes, `mipmap-${dpi}`);
      mkdirSync(dir, { recursive: true });
      if (!manual) {
        await renderPng(sharp, iconSvg(spec, px), path.join(dir, "ic_launcher.png"));
        await renderPng(sharp, iconSvg(spec, px, { round: true }), path.join(dir, "ic_launcher_round.png"));
      }
      // foreground adaptive: حرف سفید روی شفاف — داخل safe zone مرکزی
      await renderPng(sharp, iconSvg(spec, px, { transparent: true }), path.join(dir, "ic_launcher_foreground.png"));
    }

    // adaptive icon XML — بدون این، مانیفست به ic_launcher.xml کندو (زنبور) اشاره می کرد
    const anydpi = path.join(brandRes, "mipmap-anydpi-v26");
    mkdirSync(anydpi, { recursive: true });
    const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>`;
    writeFileSync(path.join(anydpi, "ic_launcher.xml"), adaptive);
    writeFileSync(path.join(anydpi, "ic_launcher_round.xml"), adaptive);

    // رنگ پس زمینه آیکون = primary برند
    writeFileSync(
      path.join(brandRes, "values", "ic_launcher_background.xml"),
      `<?xml version='1.0' encoding='utf-8'?>
<resources><color name="ic_launcher_background">${b.colors.primary}</color></resources>
`
    );

    // اسپلش برنددار در همه باکت ها
    for (const [bucket, w, h] of splashBuckets) {
      const dir = path.join(brandRes, bucket);
      mkdirSync(dir, { recursive: true });
      await renderPng(sharp, splashSvg(spec, w, h), path.join(dir, "splash.png"));
    }

    // آیکون نوتیفیکیشن مونوکروم
    const drawableDir = path.join(brandRes, "drawable");
    mkdirSync(drawableDir, { recursive: true });
    await renderPng(sharp, notificationSvg(spec, 96), path.join(drawableDir, "ic_notification.png"));

    // مانیفست برند — آیکون/رنگ نوتیفیکیشن برای آینده (merge با مانیفست اصلی)
    writeFileSync(
      path.join(androidApp, "src", b.id, "AndroidManifest.xml"),
      `<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
    <application>
        <meta-data android:name="com.google.firebase.messaging.default_notification_icon"
                   android:resource="@drawable/ic_notification" />
        <meta-data android:name="com.google.firebase.messaging.default_notification_color"
                   android:resource="@color/ic_launcher_background" />
    </application>
</manifest>
`
    );

    console.log(`[brands] icons+splash for ${b.id} → android/app/src/${b.id}/res/`);
  }
}

function randomPass() {
  return Math.random().toString(36).slice(2, 14) + Math.random().toString(36).slice(2, 6).toUpperCase();
}

function escapeXml(s) {
  return String(s)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

if (!process.argv.includes("--no-icons")) {
  await generateIcons();
}

// ---------- گزارش خروجی ها ----------
console.log("\n[brands] build variants:");
console.log(`  userDirect    → com.kandoochats.app (کندو چت — Kandoo Chat — KandooPay)`);
console.log(`  adminDirect   → com.kandoo.admin (مدیریت)`);
for (const b of brands) {
  for (const m of MARKETS) {
    console.log(`  ${flavor(b, m).padEnd(14)}→ ${b.packageName} (${b.name} — ${m} IAP)`);
  }
}
console.log("\n[brands] done. Run: npm run build:brands");
